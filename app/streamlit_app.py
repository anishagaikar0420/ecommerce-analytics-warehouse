"""Interactive dashboard over the exported KPI CSVs. Run `make run` first, then `make app`."""
from pathlib import Path

import pandas as pd
import plotly.express as px
import streamlit as st

OUT = Path(__file__).resolve().parents[1] / "output"
st.set_page_config(page_title="E-Commerce Analytics Warehouse", layout="wide")


@st.cache_data
def load(name: str) -> pd.DataFrame:
    return pd.read_csv(OUT / f"{name}.csv")


if not (OUT / "monthly_revenue.csv").exists():
    st.error("No output/ folder found. Run `make run` first.")
    st.stop()

st.title("E-Commerce Analytics Warehouse")
st.caption("Synthetic data generated by the pipeline · completed orders only · source: sql/analytics.sql")

monthly, aov = load("monthly_revenue"), load("average_order_value")
months = sorted(monthly["year_month"])
lo, hi = st.select_slider("Month range", options=months, value=(months[0], months[-1]))
m = monthly[monthly["year_month"].between(lo, hi)]

c1, c2, c3, c4 = st.columns(4)
c1.metric("Revenue", f"${m['revenue'].sum():,.0f}")
c2.metric("Completed orders", f"{m['orders'].sum():,}")
c3.metric("Average order value", f"${m['revenue'].sum() / m['orders'].sum():,.2f}")
c4.metric("Repeat purchase rate", f"{load('repeat_purchase_rate')['repeat_rate_pct'].iloc[0]}%")

t1, t2, t3 = st.tabs(["Revenue", "Products & categories", "Customers"])
with t1:
    metric = st.multiselect("Series", ["revenue", "gross_profit"], default=["revenue", "gross_profit"])
    st.plotly_chart(px.line(m, x="year_month", y=metric, markers=True, labels={"value": "USD", "year_month": ""}), use_container_width=True)
    st.plotly_chart(px.line(aov[aov["year_month"].between(lo, hi)], x="year_month", y="aov", markers=True, title="Average order value",
                            labels={"aov": "USD", "year_month": ""}), use_container_width=True)
with t2:
    a, b = st.columns(2)
    a.plotly_chart(px.bar(load("revenue_by_category"), x="revenue", y="category", orientation="h", title="Revenue by category").update_yaxes(autorange="reversed"), use_container_width=True)
    b.plotly_chart(px.bar(load("top_products"), x="revenue", y="product_name", orientation="h", title="Top 10 products").update_yaxes(autorange="reversed"), use_container_width=True)
    st.dataframe(load("gross_margin_by_category"), use_container_width=True, hide_index=True)
with t3:
    coh = load("customer_cohort_retention").pivot(index="cohort_month", columns="months_since_first", values="retention_pct")
    st.plotly_chart(px.imshow(coh.iloc[:, 1:], color_continuous_scale="Blues", aspect="auto", zmax=coh.iloc[:, 1:].stack().quantile(0.95),
                              title="Cohort retention % (months since first purchase; month 0 = 100% omitted)",
                              labels={"x": "Months since first purchase", "y": "Cohort", "color": "Retention %"}), use_container_width=True)
    a, b = st.columns(2)
    a.plotly_chart(px.bar(load("revenue_by_country"), x="country", y="revenue", title="Revenue by country"), use_container_width=True)
    b.dataframe(load("top_customers_ltv"), use_container_width=True, hide_index=True)
