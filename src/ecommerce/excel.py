"""Build an Excel workbook (live formulas + native Excel charts) from the exported KPI CSVs."""
from pathlib import Path

import duckdb
import xlsxwriter


def _fetch(con, csv: Path):
    cur = con.execute(f"SELECT * FROM read_csv('{csv}')")
    return [d[0] for d in cur.description], cur.fetchall()


def _chart(wb, kind, title, ws_name, n, cat_col, val_cols, names, y_title=None, num_format=None):
    ch = wb.add_chart({"type": kind})
    for col, name in zip(val_cols, names):
        ch.add_series({"name": name, "categories": [ws_name, 1, cat_col, n, cat_col], "values": [ws_name, 1, col, n, col]})
    ch.set_title({"name": title, "name_font": {"size": 12}})
    ch.set_legend({"position": "bottom"} if len(val_cols) > 1 else {"none": True})
    ch.set_y_axis({"num_format": num_format or "General", "major_gridlines": {"visible": True, "line": {"color": "#DDDDDD"}}, "name": y_title})
    ch.set_size({"width": 620, "height": 340})
    return ch


def build_workbook(output_dir: Path, path: Path) -> Path:
    con = duckdb.connect(":memory:")
    path.parent.mkdir(parents=True, exist_ok=True)
    wb = xlsxwriter.Workbook(str(path))
    hdr = wb.add_format({"bold": True, "bg_color": "#1C5CAB", "font_color": "#FFFFFF", "border": 1})
    money, money2 = wb.add_format({"num_format": "$#,##0"}), wb.add_format({"num_format": "$#,##0.00"})
    pct, intf = wb.add_format({"num_format": "0.0%"}), wb.add_format({"num_format": "#,##0"})
    fmts = {"revenue": money, "gross_profit": money, "aov": money2, "lifetime_value": money}

    def table(ws, cols, rows):
        for j, c in enumerate(cols):
            ws.write(0, j, c, hdr)
            ws.set_column(j, j, max(14, len(c) + 4))
        for i, r in enumerate(rows, start=1):
            for j, v in enumerate(r):
                ws.write(i, j, v, fmts.get(cols[j]))

    ws_sum = wb.add_worksheet("Summary")
    data = {}
    specs = [("Monthly", "monthly_revenue", "line", "Monthly revenue and gross profit", [1, 2], ["Revenue", "Gross profit"], "$#,##0"),
             ("AOV", "average_order_value", "line", "Average order value", [1], ["AOV"], "$#,##0"),
             ("Category", "revenue_by_category", "column", "Revenue by category", [1], ["Revenue"], "$#,##0"),
             ("Top Products", "top_products", "bar", "Top 10 products by revenue", [3], ["Revenue"], "$#,##0"),
             ("Country", "revenue_by_country", "column", "Revenue by country", [2], ["Revenue"], "$#,##0")]
    for sheet, csv, kind, title, vals, names, nf in specs:
        ws = wb.add_worksheet(sheet)
        cols, rows = _fetch(con, output_dir / f"{csv}.csv")
        table(ws, cols, rows)
        data[sheet] = len(rows)
        ws.insert_chart(1, len(cols) + 1, _chart(wb, kind, title, sheet, len(rows), 0, vals, names, num_format=nf))
    ws = wb.get_worksheet_by_name("Monthly")
    ws.write(0, 4, "gross_margin_pct", hdr); ws.set_column(4, 4, 18)
    for i in range(1, data["Monthly"] + 1):
        ws.write_formula(i, 4, f"=C{i + 1}/B{i + 1}", pct)
    ws.insert_chart(1, 6, _chart(
        wb, "line", "Monthly revenue and gross profit", "Monthly", data["Monthly"], 0, [1, 2], ["Revenue", "Gross profit"], num_format="$#,##0"))

    # Cohort retention as a Cohort x Month matrix with a colour-scale heatmap
    wc = wb.add_worksheet("Cohort Retention")
    _, rows = _fetch(con, output_dir / "customer_cohort_retention.csv")
    cohorts = sorted({r[0] for r in rows}); maxm = max(r[1] for r in rows)
    wc.write(0, 0, "cohort_month", hdr); wc.set_column(0, 0, 14)
    for m in range(maxm + 1):
        wc.write(0, m + 1, m, hdr)
    idx = {c: i + 1 for i, c in enumerate(cohorts)}
    for c, m, _, rp in rows:
        wc.write(idx[c], m + 1, rp / 100, pct)
    for c, i in idx.items():
        wc.write(i, 0, c)
    wc.conditional_format(1, 2, len(cohorts), maxm + 1, {"type": "2_color_scale", "min_color": "#CDE2FB", "max_color": "#0D366B"})
    wc.write(len(cohorts) + 2, 0, "Columns = months since first purchase; month 0 is always 100% (excluded from the colour scale).")
    wc.freeze_panes(1, 1)

    # Summary sheet: formulas referencing the data sheets, so numbers update if data changes
    n = data["Monthly"] + 1
    ws_sum.set_column(0, 0, 34); ws_sum.set_column(1, 1, 18)
    ws_sum.write(0, 0, "E-Commerce Analytics Warehouse - KPI summary", wb.add_format({"bold": True, "font_size": 14}))
    ws_sum.write(1, 0, "Synthetic data generated by the pipeline. Completed orders only.")
    _, rr = _fetch(con, output_dir / "repeat_purchase_rate.csv")
    ws_sum.write(3, 0, "Revenue", hdr); ws_sum.write_formula(3, 1, f"=SUM(Monthly!B2:B{n})", money)
    ws_sum.write(4, 0, "Gross profit", hdr); ws_sum.write_formula(4, 1, f"=SUM(Monthly!C2:C{n})", money)
    ws_sum.write(5, 0, "Gross margin", hdr); ws_sum.write_formula(5, 1, "=B5/B4", pct)
    ws_sum.write(6, 0, "Completed orders", hdr); ws_sum.write_formula(6, 1, f"=SUM(Monthly!D2:D{n})", intf)
    ws_sum.write(7, 0, "Average order value", hdr); ws_sum.write_formula(7, 1, "=B4/B7", money2)
    ws_sum.write(8, 0, "Repeat purchase rate", hdr); ws_sum.write(8, 1, rr[0][2] / 100, pct)
    ws_sum.insert_chart(10, 0, _chart(wb, "line", "Monthly revenue", "Monthly", data["Monthly"], 0, [1], ["Revenue"], num_format="$#,##0"))
    wb.close()
    return path
